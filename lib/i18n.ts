const DICTS: Record<Lang, Dict> = { en, hi, te };

export const LANGS: { id: Lang; label: string }[] = [
  { id: "en", label: "English" },
  { id: "hi", label: "हिन्दी" },
  { id: "te", label: "తెలుగు" },
];

export function t(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  const template = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** Dynamic keys such as `state_${state}`; unknown keys fall back to the provided text. */
export function tk(lang: Lang, key: string, fallback: string, vars?: Record<string, string | number>): string {
  return key in en ? t(lang, key as I18nKey, vars) : fallback;
}

/** Translate a server error code, falling back to the server's own message. */
export function errorText(lang: Lang, code: string | undefined, fallback: string): string {
  return code ? tk(lang, `err_${code}`, fallback) : fallback;
}

export function missingKeys(lang: Lang): string[] {
  return (Object.keys(en) as I18nKey[]).filter((k) => !(k in DICTS[lang]));
}
